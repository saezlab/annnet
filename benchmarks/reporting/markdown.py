def _summary(records: list[dict], plots_dir: Path) -> list[str]:
    scales = scales_in(records)
    comparable = engines_in(records, ops=COMPARABLE_OPS)
    timed = [r for r in records if r.get('time')]
    memory = [r for r in records if r.get('memory')]
    skipped = [r for r in records if r.get('status') == 'skipped']
    graph_tool = 'yes' if 'graph-tool' in comparable else 'not in comparable records'

    lines = [
        '## Summary',
        '',
        '| item | value |',
        '|---|---|',
        f'| records | {len(records)} total, {len(timed)} timed, {len(memory)} memory, {len(skipped)} skipped |',
        f'| scales | {", ".join(scales) if scales else "-"} |',
        f'| comparable engines | {", ".join(engine_label(e) for e in comparable) or "-"} |',
        f'| graph-tool comparable run | {graph_tool} |',
        '',
    ]
    lines += _ratio_snapshot(records)
    lines += _plot_shortlist(records, plots_dir)
    return lines


def _ratio_snapshot(records: list[dict]) -> list[str]:
    idx = index_records(records)
    scales = scales_in(records)
    if not scales:
        return []
    scale = scales[-1]
    baselines = [
        engine for engine in BASELINE_ENGINES if engine in engines_in(records, ops=COMPARABLE_OPS)
    ]
    if not baselines:
        return []
    lines = [
        f'### Largest Scale Snapshot ({scale})',
        '',
        '| op | ' + ' | '.join(ratio_label(engine) for engine in baselines) + ' |',
        '|---' + '|---' * len(baselines) + '|',
    ]
    for op in ('build', 'neighbors', 'has_edge', 'enumerate_edges'):
        ann = median_ms(pick(idx, 'annnet', scale, op))
        ratios = []
        for baseline in baselines:
            base = median_ms(pick(idx, baseline, scale, op))
            ratios.append(f'{ann / base:.2f}x' if (ann and base) else '-')
        lines.append(f'| {op} | ' + ' | '.join(ratios) + ' |')
    lines.append('')
    return lines


def _plot_shortlist(records: list[dict], plots_dir: Path) -> list[str]:
    if len(scales_in(records)) < 2:
        return []
    links = [
        ('Comparable operation scaling', plots_dir / 'scaling_wall_time_overview.png'),
        ('Retained memory scaling', plots_dir / 'memory_retained_scaling.png'),
        ('Memory density', plots_dir / 'memory_bytes_per_edge.png'),
    ]
    for baseline in BASELINE_ENGINES:
        if baseline in engines_in(records, ops=COMPARABLE_OPS, require_metric=True):
            links.insert(
                1,
                (
                    f'{ratio_label(baseline)} heatmap',
                    plots_dir / f'annnet_vs_{slug(baseline)}_ratio_heatmap.png',
                ),
            )
    lines = ['### Key Plots', '', '| plot | path |', '|---|---|']
    for label, path in links:
        lines.append(f'| {label} | `{rel(path, plots_dir.parent)}` |')
    lines.append('')
    return lines


def _head_to_head(idx: dict, records: list[dict]) -> list[str]:
    engines = engines_in(records, ops=COMPARABLE_OPS)
    if not engines:
        return []
    baselines = [engine for engine in BASELINE_ENGINES if engine in engines]
    baseline_text = ', '.join(engine_label(engine) for engine in baselines) or 'installed baselines'
    lines = [
        f'## Head-to-head (AnnNet vs {baseline_text})',
        '',
        'Median per-call time on semantically comparable operations. Ratio columns are '
        'AnnNet divided by the named baseline; values above 1x mean AnnNet is slower.',
        '',
    ]
    value_columns = [engine_label(engine) for engine in engines]
    ratio_columns = [ratio_label(engine) for engine in baselines]
    for scale in scales_in(records):
        n_e = next((r['n_edges'] for r in records if r['scale'] == scale), '?')
        lines += [
            f'### scale = {scale} (~{n_e} edges)',
            '',
            '| op | ' + ' | '.join(value_columns + ratio_columns) + ' |',
            '|---' + '|---' * (len(value_columns) + len(ratio_columns)) + '|',
        ]
        for op in COMPARABLE_OPS:
            ann_ms = median_ms(pick(idx, 'annnet', scale, op))
            values = [fmt_ms(median_ms(pick(idx, engine, scale, op))) for engine in engines]
            ratios = []
            for baseline in baselines:
                base_ms = median_ms(pick(idx, baseline, scale, op))
                ratios.append(f'{ann_ms / base_ms:.2f}x' if (ann_ms and base_ms) else '-')
            lines.append(f'| {op} | ' + ' | '.join(values + ratios) + ' |')
        lines.append('')
    return lines


def _memory(idx: dict, records: list[dict]) -> list[str]:
    engines = engines_in(records, ops=['footprint'], require_metric=True)
    if not engines:
        return []
    lines = [
        '## Memory Footprint',
        '',
        'Retained allocation for the built graph and retained bytes per edge. AnnNet '
        'stores endpoints, weights, incidence/matrix state, and annotation columns; '
        'the external graph libraries store adjacency-oriented representations.',
        '',
    ]
    for scale in scales_in(records):
        rows = []
        for engine in engines:
            r = pick(idx, engine, scale, 'footprint')
            if not r or not r.get('memory'):
                continue
            m = r['memory']
            n_e = r['n_edges'] or 1
            rows.append(
                (
                    engine,
                    m['retained_bytes'],
                    m['retained_bytes'] / n_e,
                    m['peak_bytes'],
                    m['rss_delta_bytes'],
                )
            )
        if not rows:
            continue
        n_e = next((r['n_edges'] for r in records if r['scale'] == scale), '?')
        lines += [
            f'### scale = {scale} (~{n_e} edges)',
            '',
            '| engine | retained | bytes/edge | peak | rss delta |',
            '|---|---|---|---|---|',
        ]
        for engine, ret, bpe, peak, rss in rows:
            lines.append(
                f'| {engine_label(engine)} | {fmt_bytes(ret)} | {bpe:.1f} | '
                f'{fmt_bytes(peak)} | {fmt_bytes(rss)} |'
            )
        lines.append('')
    return lines


def _annnet_internals(idx: dict, records: list[dict]) -> list[str]:
    lines = [
        '## AnnNet-only Capabilities',
        '',
        'Operations the external graph libraries cannot express directly. These are '
        'feature costs, not baseline comparisons.',
        '',
    ]
    for scale in scales_in(records):
        body = []
        for op in ANNNET_INTERNAL_ORDER:
            r = pick(idx, 'annnet', scale, op)
            if not r:
                continue
            note = r.get('note', '')
            disk = r.get('disk_bytes')
            extra = f' ; disk {fmt_bytes(disk)}' if disk else ''
            body.append(f'| {op} | {fmt_ms(median_ms(r))} | {note}{extra} |')
        if not body:
            continue
        lines += [f'### scale = {scale}', '', '| op | median | note |', '|---|---|---|']
        lines += body + ['']
    return lines


def _feature_section(records: list[dict], group: str, title: str, blurb: str) -> list[str]:
    by_scale = {}
    for r in records:
        if r.get('engine') == 'annnet' and r.get('group') == group and r.get('time'):
            by_scale.setdefault(r['scale'], []).append(r)
    if not by_scale:
        return []
    lines = [f'## {title}', '', blurb, '']
    for scale in scales_in(records):
        body = by_scale.get(scale)
        if not body:
            continue
        lines += [f'### scale = {scale}', '', '| op | median | note |', '|---|---|---|']
        for r in body:
            lines.append(f'| {r["op"]} | {fmt_ms(median_ms(r))} | {r.get("note", "")} |')
        lines.append('')
    return lines


def _extra_dimensions(records: list[dict]) -> list[str]:
    lines = []
    for group, title, blurb in EXTRA_GROUPS:
        by_scale = {}
        for r in records:
            if r.get('group') == group:
                by_scale.setdefault(r['scale'], []).append(r)
        if not by_scale:
            continue
        lines += [f'## {title}', '', blurb, '']
        for scale in scales_in(records):
            body = by_scale.get(scale)
            if not body:
                continue
            lines += [
                f'### scale = {scale}',
                '',
                '| engine | op | median | status | note |',
                '|---|---|---|---|---|',
            ]
            for r in body:
                median = fmt_ms(median_ms(r)) if r.get('time') else '-'
                status = r.get('status', 'ok' if r.get('time') else 'skipped')
                note = r.get('note', '')
                if r.get('reason'):
                    note = f'{note}; {r["reason"]}' if note else r['reason']
                if r.get('error'):
                    note = f'{note}; ERROR: {r["error"]}' if note else f'ERROR: {r["error"]}'
                lines.append(
                    f'| {engine_label(r["engine"])} | {r["op"]} | {median} | {status} | {note} |'
                )
            lines.append('')
    return lines


def _io_formats(payload: dict) -> list[str]:
    recs = payload.get('io_formats')
    if not recs:
        return []
    n_e = next((r.get('n_edges') for r in recs if r.get('n_edges')), '?')
    lines = [
        '## IO Formats',
        '',
        f'Write/read median time, on-disk size, and edge-count fidelity for a ~{n_e}-edge graph.',
        '',
        '| format | write | read | size | edges ok | note |',
        '|---|---|---|---|---|---|',
    ]
    for r in recs:
        if r.get('error'):
            lines.append(f'| {r["format"]} | - | - | - | - | ERROR: {r["error"]} |')
            continue
        lines.append(
            f'| {r["format"]} | {fmt_ms(ms(r.get("write")))} | {fmt_ms(ms(r.get("read")))} '
            f'| {fmt_bytes(r.get("size_bytes"))} | {"yes" if r.get("edges_ok") else "no"} '
            f'| {r.get("note", "")} |'
        )
    lines.append('')
    return lines


def _adapters(payload: dict) -> list[str]:
    recs = payload.get('adapters')
    if not recs:
        return []
    n_e = next((r.get('n_edges') for r in recs if r.get('n_edges')), '?')
    lines = [
        '## Adapter Conversions',
        '',
        f'Export/import median time for graph-library bridges (~{n_e} edges). '
        'Uninstalled backends are skipped.',
        '',
        '| adapter | export | import | edges ok | note |',
        '|---|---|---|---|---|',
    ]
    for r in recs:
        if r.get('skipped'):
            lines.append(f'| {r["adapter"]} | skipped | | | {r["skipped"]} |')
            continue
        if r.get('error'):
            lines.append(f'| {r["adapter"]} | - | - | - | ERROR: {r["error"]} |')
            continue
        ok = 'yes' if r.get('edges_ok') else ('-' if r.get('direction') == 'export' else 'no')
        lines.append(
            f'| {r["adapter"]} | {fmt_ms(ms(r.get("export")))} | {fmt_ms(ms(r.get("import")))} '
            f'| {ok} | {r.get("note", "")} |'
        )
    lines.append('')
    return lines


def _mutation_ratios(idx: dict, records: list[dict]) -> list[str]:
    """AnnNet against every reference library, per single-element operation."""
    present = engines_in(records, ops=MUTATION_OPS)
    if 'annnet' not in present:
        return []
    baselines = [engine for engine in BASELINE_ENGINES if engine in present]
    lines = [
        '## Single-element writes',
        '',
        'A bulk build hides the per-element cost. These rows measure one write on a',
        'freshly built graph, so the number is what a user pays when a graph grows one',
        'edge at a time. `read_after_mutate` performs one write and then one read of a',
        'derived matrix, which is the adverse case for a core that rebuilds on a stale',
        'read.',
        '',
    ]
    for scale in scales_in(records):
        header = ['op', 'annnet ms']
        header += [ratio_label(engine) for engine in baselines]
        lines += [
            f'### {scale}',
            '',
            '| ' + ' | '.join(header) + ' |',
            '|---' * len(header) + '|',
        ]
        for op in MUTATION_OPS:
            ann = median_ms(pick(idx, 'annnet', scale, op))
            row = [op, f'{ann:.3f}' if ann else '-']
            for baseline in baselines:
                base = median_ms(pick(idx, baseline, scale, op))
                row.append(f'{ann / base:.2f}x' if (ann and base) else '-')
            lines.append('| ' + ' | '.join(row) + ' |')
        lines.append('')
    return lines


def _growth_rows(records: list[dict], group: str) -> list[dict]:
    return [
        row
        for row in records
        if row.get('group') == group and row.get('status') == 'ok' and row.get('time')
    ]


def _matrix_growth(records: list[dict]) -> list[str]:
    """Show whether reading the matrix after every write stays linear."""
    rows = _growth_rows(records, 'matrix_growth')
    if not rows:
        return []
    by_size: dict[int, dict[str, float]] = {}
    for row in rows:
        by_size.setdefault(row['n_edges'], {})[row['op']] = row['time']['median_s'] * 1000.0
    lines = [
        '## Reading the matrix after every write',
        '',
        'A core that rebuilds the matrix on a stale read makes the second column grow',
        'with the square of N, and the ratio grows with N. A core whose member lists are',
        'the matrix keeps the ratio flat.',
        '',
        '| N appends | appends only ms | append then read ms | ratio |',
        '|---|---|---|---|',
    ]
    for size in sorted(by_size):
        pair = by_size[size]
        only = pair.get('append_only')
        both = pair.get('append_then_read')
        ratio = f'{both / only:.1f}x' if (only and both) else '-'
        lines.append(
            f'| {size} | {only:.2f} | {both:.2f} | {ratio} |'
            if (only and both)
            else f'| {size} | - | - | - |'
        )
    lines.append('')
    return lines


def _matrix_cache(records: list[dict]) -> list[str]:
    """Show where extending a cached matrix stops beating a full re-map."""
    rows = _growth_rows(records, 'matrix_cache')
    if not rows:
        return []
    by_note: dict[str, dict[str, float]] = {}
    for row in rows:
        by_note.setdefault(row['note'], {})[row['op']] = row['time']['median_s'] * 1000.0
    lines = [
        '## The append-only matrix cache',
        '',
        'The crossing point of these two columns is the number of appended columns that',
        'makes dropping the cache cheaper than keeping it.',
        '',
        '| appended | extend ms | re-map ms | extend is |',
        '|---|---|---|---|',
    ]
    for note in sorted(by_note, key=lambda text: int(text.split()[0])):
        pair = by_note[note]
        extend = pair.get('cache_extend')
        remap = pair.get('cache_remap')
        verdict = '-'
        if extend and remap:
            verdict = (
                f'{remap / extend:.1f}x faster'
                if extend < remap
                else f'{extend / remap:.1f}x slower'
            )
        lines.append(
            f'| {note.split()[0]} | {extend:.3f} | {remap:.3f} | {verdict} |'
            if (extend and remap)
            else f'| {note.split()[0]} | - | - | - |'
        )
    lines.append('')
    return lines


def _attribute_options(records: list[dict]) -> list[str]:
    """The two candidate attribute stores, side by side."""
    rows = _growth_rows(records, 'attribute_options')
    baselines = _attribute_baselines(records)
    if not rows and not baselines:
        return []
    lines = ['## Attribute storage', '']
    if rows:
        table: dict[str, dict[str, float]] = {}
        for row in rows:
            option = row['note'].split(';')[0]
            table.setdefault(option, {})[row['op']] = row['time']['median_s'] * 1000.0
        lines += [
            'One typed array per attribute against an append-only journal of facts. The',
            'journal pays a fold on every whole-frame read, so a tight alternation of one',
            'write and one full read is its adverse case.',
            '',
            '| option | single write ms | whole-frame read ms |',
            '|---|---|---|',
        ]
        for option in sorted(table):
            pair = table[option]
            write = pair.get('attr_write_single')
            read = pair.get('attr_read_frame')
            lines.append(
                f'| {option} | {write:.5f} | {read:.3f} |'
                if (write is not None and read is not None)
                else f'| {option} | - | - |'
            )
        lines.append('')
    lines += baselines
    return lines


# The three operations of the attribute benchmark, in the order the report shows
# them, with the heading each takes.
_ATTRIBUTE_OP_LABELS = (
    ('column_read', 'read the column'),
    ('column_op', 'sum a column already held'),
    ('column_read_and_op', 'read and sum'),
)


def _attribute_baselines(records: list[dict]) -> list[str]:
    """The same three operations, one column per named baseline.

    Every number here says which library produced it, and the read is reported
    apart from the operation, so a ratio says which of the two it comes from. A
    baseline whose library is absent keeps its column and shows ``skipped``,
    because a row that vanishes with a library would make a short run look like
    a complete one.
    """
    rows = [row for row in records if row.get('group') == 'attributes' and row.get('baseline')]
    if not rows:
        return []

    baselines = [
        baseline
        for baseline in ('annnet', 'polars', 'pandas', 'pyarrow', 'numpy')
        if any(row['baseline'] == baseline for row in rows)
    ]
    held: dict[tuple[str, str], dict] = {(row['op'], row['baseline']): row for row in rows}
    subject = 'annnet'

    # The ceiling of SC-001 is against a contiguous array of the same length, so
    # that is the ratio the table carries, and it says so in the heading rather
    # than leaving a reader to guess which bar it is against.
    against = 'numpy' if 'numpy' in baselines else None
    header = ' | '.join(engine_label(baseline) + ' ms' for baseline in baselines)
    ratio_heading = f'AnnNet / {engine_label(against)}' if against else 'ratio'
    lines = [
        'The same operation on an attribute column and on a column of each dataframe',
        'library the package declares, plus a bare numpy array as the floor. The read of',
        'the column and the operation on it are separate rows, so a ratio says which of',
        'the two it comes from. A library that is not installed is named and skipped.',
        '',
        f'| operation | {header} | {ratio_heading} |',
        '|---' * (len(baselines) + 2) + '|',
    ]
    for op, label in _ATTRIBUTE_OP_LABELS:
        cells = [_attribute_cell(held.get((op, baseline))) for baseline in baselines]
        mine = _attribute_ms(held.get((op, subject)))
        theirs = _attribute_ms(held.get((op, against))) if against else None
        ratio = f'{mine / theirs:.2f}x' if (mine and theirs) else '-'
        lines.append(f'| {label} | ' + ' | '.join(cells) + f' | {ratio} |')
    lines.append('')
    return lines


def _attribute_ms(row: dict | None) -> float | None:
    if not row or row.get('status') != 'ok' or not row.get('time'):
        return None
    return row['time']['median_s'] * 1000.0


def _attribute_cell(row: dict | None) -> str:
    if row is None:
        return '-'
    if row.get('status') == 'skipped':
        return 'skipped'
    value = _attribute_ms(row)
    return '-' if value is None else f'{value:.4f}'
